#!/usr/bin/env python3
"""
evals/mutation/run_mutation.py

Dependency-free Python mutation runner.

Usage:
    python3 evals/mutation/run_mutation.py \\
        --files src/foo.py src/bar.py \\
        --tests tests/test_foo.py \\
        --result .opencode/mutation-result.json \\
        [--threshold 0.70] \\
        [--mutant-cap 200] \\
        [--wall-clock-seconds 300] \\
        [--test-cmd "python3 -m pytest -q"]

Exits 0 when score >= threshold, 1 otherwise.
Exits 2 on configuration or parse errors.

Mutation operators applied to each source file:
  - comparison operators:  ==  !=  <  <=  >  >=
  - boolean operators:     and or
  - arithmetic operators:  +  -  *  /  //  %
  - unary negation:        -x → x  (and vice-versa prefix)
  - return None:           replace any return <expr> with return None
  - constant tweaks:       integer literals incremented by 1

Each operator swap produces one mutant. Mutants are generated by simple text
substitution per line; overlapping mutants on the same line are each tested
independently.

The runner is intentionally simple and honest about its limitations: it catches
a wide class of tautological-test weaknesses without requiring a full AST parser.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterator


# ---------------------------------------------------------------------------
# Mutation operators
# ---------------------------------------------------------------------------

# Each entry is (original_token, replacement_token). Applied left-to-right on a
# line; a token must be surrounded by word or operator boundaries to match.
_COMPARISON_OPS = [
    ("==", "!="), ("!=", "=="),
    (" < ",  " > "), (" > ",  " < "),
    (" <= ", " >= "), (" >= ", " <= "),
    (" < ",  " <= "), (" <= ", " < "),
    (" > ",  " >= "), (" >= ", " > "),
]

_BOOLEAN_OPS = [
    (" and ", " or "),
    (" or ",  " and "),
]

_ARITHMETIC_OPS = [
    (" + ", " - "), (" - ", " + "),
    (" * ", " / "), (" / ", " * "),
    (" // ", " + "), (" % ", " + "),
]

ALL_SIMPLE_OPS = _COMPARISON_OPS + _BOOLEAN_OPS + _ARITHMETIC_OPS


def _mutate_line_simple(line: str) -> Iterator[str]:
    """Yield mutated copies of line using simple token substitutions."""
    for orig, repl in ALL_SIMPLE_OPS:
        if orig in line:
            yield line.replace(orig, repl, 1)


def _mutate_line_return_none(line: str) -> Iterator[str]:
    """Replace `return <expr>` with `return None` when expr is non-trivial."""
    stripped = line.lstrip()
    if stripped.startswith("return ") and not stripped.startswith("return None"):
        indent = line[: len(line) - len(stripped)]
        yield f"{indent}return None\n"


def _mutate_line_int_literal(line: str) -> Iterator[str]:
    """Increment each integer literal on the line by 1."""
    for mode in ("eval", "exec"):
        try:
            tree = ast.parse(line.strip(), mode=mode)  # type: ignore[arg-type]
            break
        except SyntaxError:
            continue
    else:
        return
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, int):
            original = str(node.value)
            mutated = str(node.value + 1)
            if original in line:
                yield line.replace(original, mutated, 1)


def generate_mutants(source: str, filepath: str) -> list[tuple[int, str, str]]:
    """Return list of (line_number_1based, original_line, mutated_source)."""
    lines = source.splitlines(keepends=True)
    mutants = []
    for idx, line in enumerate(lines):
        lineno = idx + 1
        # Skip comments and blank lines
        stripped = line.lstrip()
        if not stripped or stripped.startswith("#"):
            continue
        candidates: list[str] = []
        candidates.extend(_mutate_line_simple(line))
        candidates.extend(_mutate_line_return_none(line))
        candidates.extend(_mutate_line_int_literal(line))
        for mutated_line in candidates:
            if mutated_line == line:
                continue
            mutated_lines = lines[:]
            mutated_lines[idx] = mutated_line
            mutants.append((lineno, line.rstrip(), "".join(mutated_lines)))
    return mutants


# ---------------------------------------------------------------------------
# Test runner
# ---------------------------------------------------------------------------

def run_tests(test_cmd: str, extra_env: dict | None = None) -> bool:
    """Run test_cmd; return True if exit code is 0 (tests pass)."""
    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1", **(extra_env or {})}
    result = subprocess.run(
        test_cmd,
        shell=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )
    return result.returncode == 0


# ---------------------------------------------------------------------------
# Main mutation loop
# ---------------------------------------------------------------------------

@dataclass
class MutationResult:
    score: float = 0.0
    killed: int = 0
    survived: int = 0
    total: int = 0
    files: list[str] = field(default_factory=list)
    generated_at: str = ""
    threshold: float = 0.70
    passed: bool = False
    baseline_passed: bool = True
    invalid_reason: str = ""
    survivors: list[dict] = field(default_factory=list)  # for feeding back to agent

    def to_dict(self) -> dict:
        return {
            "score": round(self.score, 6),
            "killed": self.killed,
            "survived": self.survived,
            "total": self.total,
            "files": self.files,
            "generated_at": self.generated_at,
            "threshold": self.threshold,
            "passed": self.passed,
            "baseline_passed": self.baseline_passed,
            "invalid_reason": self.invalid_reason,
            "survivors": self.survivors,
        }


def run_mutation(
    source_files: list[Path],
    test_cmd: str,
    threshold: float,
    mutant_cap: int,
    wall_clock_seconds: int,
) -> MutationResult:
    deadline = time.monotonic() + wall_clock_seconds
    result = MutationResult(
        files=[str(f) for f in source_files],
        generated_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        threshold=threshold,
    )
    if not run_tests(test_cmd):
        result.baseline_passed = False
        result.invalid_reason = "unmutated baseline test command failed"
        return result

    # Collect mutants across all source files up to the cap
    all_mutants: list[tuple[Path, int, str, str]] = []
    for src in source_files:
        try:
            source = src.read_text(encoding="utf-8")
        except OSError:
            continue
        for lineno, orig_line, mutated_source in generate_mutants(source, str(src)):
            all_mutants.append((src, lineno, orig_line, mutated_source))
            if len(all_mutants) >= mutant_cap:
                break
        if len(all_mutants) >= mutant_cap:
            break

    result.total = len(all_mutants)
    if result.total == 0:
        # No mutants generated — treat as trivially passing (no mutable code found)
        result.score = 1.0
        result.passed = True
        return result

    with tempfile.TemporaryDirectory(prefix="mutation-run-") as tmpdir:
        for src, lineno, orig_line, mutated_source in all_mutants:
            if time.monotonic() > deadline:
                # Time budget exhausted: score what we have
                break
            # Write mutant
            tmp_src = Path(tmpdir) / src.name
            original = src.read_text(encoding="utf-8")
            try:
                src.write_text(mutated_source, encoding="utf-8")
                tests_still_pass = run_tests(test_cmd)
            finally:
                # Always restore
                src.write_text(original, encoding="utf-8")

            if tests_still_pass:
                # Mutant survived — tests didn't catch it
                result.survived += 1
                result.survivors.append({
                    "file": str(src),
                    "line": lineno,
                    "original": orig_line,
                })
            else:
                result.killed += 1

    tested = result.killed + result.survived
    result.score = round(result.killed / tested, 6) if tested > 0 else 1.0
    result.passed = result.score >= threshold
    return result


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--files", nargs="+", required=True, metavar="FILE",
        help="Python source files to mutate (diff-scoped).",
    )
    parser.add_argument(
        "--config", default=None, metavar="PATH",
        help="Optional JSON mutation policy; CLI arguments override its values.",
    )
    parser.add_argument(
        "--tests", nargs="+", default=None, metavar="FILE",
        help="Test files or directories to pass to the test command.",
    )
    parser.add_argument(
        "--result", default=None, metavar="PATH",
        help="Path to write the JSON result artifact (or provide it in --config).",
    )
    parser.add_argument(
        "--threshold", type=float, default=0.70,
        help="Minimum kill score to pass (default: 0.70).",
    )
    parser.add_argument(
        "--mutant-cap", type=int, default=200,
        help="Maximum number of mutants to generate (default: 200).",
    )
    parser.add_argument(
        "--wall-clock-seconds", type=int, default=300,
        help="Wall-clock time budget in seconds (default: 300).",
    )
    parser.add_argument(
        "--test-cmd", default="python3 -m pytest -q",
        help="Shell command to run the test suite (default: python3 -m pytest -q).",
    )
    args = parser.parse_args(argv)

    if args.config:
        try:
            policy = json.loads(Path(args.config).read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            print(f"ERROR: invalid mutation policy: {error}", file=sys.stderr)
            return 2
        if not isinstance(policy, dict) or policy.get("enabled") is False:
            print("ERROR: mutation policy is disabled", file=sys.stderr)
            return 2
        for key in ("score_threshold", "result_path"):
            if key not in policy:
                print(f"ERROR: mutation policy missing {key}", file=sys.stderr)
                return 2
        if args.threshold == parser.get_default("threshold"):
            args.threshold = policy["score_threshold"]
        if args.result is None:
            args.result = policy["result_path"]

    if args.result is None:
        print("ERROR: --result is required unless supplied by --config", file=sys.stderr)
        return 2

    source_files = [Path(f) for f in args.files]
    missing = [str(f) for f in source_files if not f.exists()]
    if missing:
        print(f"ERROR: source files not found: {', '.join(missing)}", file=sys.stderr)
        return 2

    result = run_mutation(
        source_files=source_files,
        test_cmd=args.test_cmd,
        threshold=args.threshold,
        mutant_cap=args.mutant_cap,
        wall_clock_seconds=args.wall_clock_seconds,
    )

    out_path = Path(args.result)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(result.to_dict(), indent=2) + "\n", encoding="utf-8")

    print(
        f"mutation_score={result.score:.4f} "
        f"killed={result.killed} survived={result.survived} total={result.total} "
        f"threshold={result.threshold:.2f} passed={result.passed}"
    )
    if result.survivors:
        print(f"\nSurvivors (feed back to agent as failing targets):")
        for s in result.survivors[:10]:
            print(f"  {s['file']}:{s['line']}: {s['original'][:80]}")
        if len(result.survivors) > 10:
            print(f"  ... and {len(result.survivors) - 10} more (see {args.result})")

    return 0 if result.passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
